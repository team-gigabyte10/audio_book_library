def fetch_surah(surah_num):
    url = f"https://api.alquran.cloud/v1/surah/{surah_num}/editions/quran-uthmani,bn.bengali"
    req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
    with urllib.request.urlopen(req) as resp:
        data = json.loads(resp.read().decode('utf-8'))
        uthmani = data['data'][0]['ayahs']
        bengali = data['data'][1]['ayahs']
        return list(zip(uthmani, bengali))

def fetch_ayah(surah_num, ayah_num):
    url = f"https://api.alquran.cloud/v1/ayah/{surah_num}:{ayah_num}/editions/quran-uthmani,bn.bengali"
    req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
    with urllib.request.urlopen(req) as resp:
        data = json.loads(resp.read().decode('utf-8'))
        uth = data['data'][0]['text']
        bn = data['data'][1]['text']
        return uth, bn

def clean_arabic(text):
    # Remove sajdah / ayah end marks if any
    text = re.sub(r'[\u06DD\u06DE\u06E9]', '', text)
    # Remove Bismillah prefix from first ayah if not Surah Fatiha
    bismillah = "بِسْمِ اللَّهِ الرَّحْمَٰنِ الرَّحِيمِ"
    if text.startswith(bismillah) and len(text) > len(bismillah) + 5:
        text = text[len(bismillah):].strip()
    return text.strip()

