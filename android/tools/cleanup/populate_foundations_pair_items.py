def main():
    file_path = os.path.join("android", "app", "src", "main", "assets", "spoken_english_foundations.json")
    with open(file_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    pair_populated = 0
    pron_bn_migrated = 0

    for part in data.get("parts", []):
        for lesson in part.get("lessons", []):
            for item in lesson.get("items", []):
                item_id = item.get("id")
                # 1. Populate pair practice items
                if item_id in PAIR_DATA:
                    bn_meaning, bn_pron = PAIR_DATA[item_id]
                    item["bn"] = bn_meaning
                    item["bn_pron"] = bn_pron
                    pair_populated += 1
                
                # 2. Migrate pron_bn to bn_pron
                if "pron_bn" in item:
                    if not item.get("bn_pron"):
                        item["bn_pron"] = item["pron_bn"]
                    del item["pron_bn"]
                    pron_bn_migrated += 1

    with open(file_path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")

    print(f"Populated {pair_populated} pair practice items.")
    print(f"Migrated {pron_bn_migrated} items from 'pron_bn' to 'bn_pron'.")

if __name__ == "__main__":
    main()

